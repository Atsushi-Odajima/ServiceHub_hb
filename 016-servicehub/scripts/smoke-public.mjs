// 開発用スモーク: 公開予約フローを端末エミュレーションで通しスクリーンショットを撮る
import { chromium, devices } from '@playwright/test';
const base = process.env.BASE || 'http://localhost:3100';
const out = process.env.OUT || '/tmp';
const device = process.env.DEVICE || 'iPhone 13';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--disable-background-networking', '--disable-component-update'] });
const ctx = await browser.newContext({ ...devices[device], defaultBrowserType: undefined });
const page = await ctx.newPage();
const shot = async (n) => page.screenshot({ path: `${out}/pub-${n}.png`, fullPage: true });
await page.goto(`${base}/p/sample-wellness`);
await page.getByRole('link', { name: /新宿店/ }).click();
await page.getByRole('button', { name: /30分体験/ }).click();
await shot('1-staff');
await page.getByRole('button', { name: /おまかせ/ }).click();
await page.waitForTimeout(600);
const chips = page.locator('.date-chip');
await chips.nth(1).click();
await page.waitForSelector('.slot-btn');
await shot('2-datetime');
await page.locator('.slot-btn').first().click();
await page.getByRole('button', { name: '次へ' }).click();
await page.getByLabel('お名前').fill('スモーク テスト');
await page.getByLabel('メールアドレス').fill('smoke@example.invalid');
await page.getByLabel('電話番号').fill('090-1111-2222');
await shot('3-info');
await page.getByRole('button', { name: '確認へ' }).click();
await page.getByLabel(/上記の内容/).check();
await shot('4-confirm');
await page.waitForTimeout(3200);
await page.getByRole('button', { name: '予約する' }).click();
await page.getByText('ご予約が確定しました').waitFor();
await shot('5-done');
const manage = await page.getByRole('link', { name: /予約の確認・変更/ }).getAttribute('href');
await page.goto(base + manage);
await page.waitForTimeout(500);
await shot('6-manage');
console.log('ok', manage);
await browser.close();
